def group_for(file_path):
    """Заголовок и пояснение подсистемы по файлу, где параметр читается."""
    for path, title, about in GROUPS:
        if path == file_path:
            return title, about
    return None, None


def note_for(name):
    """Пояснение к параметру.

    Своё, написанное по разбору кода, идёт первым. Если своего нет, берётся
    пояснение из перечня заказчика — оно короче и общее, но лучше пустоты.
    Там же сказано, почему из того перечня взята только часть.
    """
    own = NOTES.get(name, "")
    if own:
        return own
    try:
        from cfgtool import vendor_notes
    except ImportError:
        return ""
    note = vendor_notes.note_for(name)
    return ("{} (из перечня заказчика)".format(note) if note else "")


def choices_for(name):
    return CHOICES.get(name)


def is_secret(name):
    return name in SECRETS
